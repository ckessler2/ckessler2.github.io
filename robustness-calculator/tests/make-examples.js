// Dev-only: regenerates the example files in ../examples.
//   node tests/make-examples.js
// The weights are seeded, so the output is identical every time.

import { writeFileSync, mkdirSync } from "node:fs";
import { model, node, tensor } from "./helpers/onnx-writer.js";
import { createRng } from "../src/attack/rng.js";

const out = new URL("../examples/", import.meta.url);
mkdirSync(out, { recursive: true });

const rng = createRng(2025);
const gauss = () => Math.sqrt(-2 * Math.log(1 - rng())) * Math.cos(2 * Math.PI * rng());
const randn = (n, scale) => Array.from({ length: n }, () => Math.fround(gauss() * scale));

// ---- float64 reference forward pass for an MLP given as layers [{W (in×out), b}]
function forward(layers, x) {
  let h = x;
  layers.forEach(({ W, b, nin, nout }, li) => {
    const o = new Array(nout).fill(0);
    for (let j = 0; j < nout; j++) {
      let s = b[j];
      for (let i = 0; i < nin; i++) s += h[i] * W[i * nout + j];
      o[j] = s;
    }
    h = li < layers.length - 1 ? o.map((v) => Math.max(0, v)) : o;
  });
  return h;
}

function mlp(name, sizes, scale) {
  const layers = [];
  for (let l = 0; l + 1 < sizes.length; l++) {
    const nin = sizes[l];
    const nout = sizes[l + 1];
    layers.push({ nin, nout, W: randn(nin * nout, scale / Math.sqrt(nin)), b: randn(nout, 0.1) });
  }
  const nodes = [];
  const inits = [];
  let cur = "input";
  layers.forEach((L, i) => {
    inits.push(tensor(`W${i}`, [L.nin, L.nout], L.W), tensor(`b${i}`, [L.nout], L.b));
    nodes.push(node("Gemm", [cur, `W${i}`, `b${i}`], [`z${i}`]));
    cur = `z${i}`;
    if (i < layers.length - 1) {
      nodes.push(node("Relu", [cur], [`h${i}`]));
      cur = `h${i}`;
    }
  });
  nodes.push(node("Identity", [cur], ["output"]));
  const bytes = model({
    nodes,
    initializers: inits,
    input: ["input", ["batch", sizes[0]]],
    output: ["output", ["batch", sizes[sizes.length - 1]]],
  });
  writeFileSync(new URL(name, out), bytes);
  return layers;
}

// ---- Example 1: 2 → 8 → 8 → 2 ReLU network and VNNLIB properties.
const tiny = mlp("tiny-relu.onnx", [2, 8, 8, 2], 1.5);
const N = 1000;
let best = -Infinity;
for (let i = 0; i <= N; i++) {
  for (let j = 0; j <= N; j++) {
    const y = forward(tiny, [-1 + (2 * i) / N, -1 + (2 * j) / N]);
    best = Math.max(best, y[0] - y[1]);
  }
}
// Lipschitz bound of y0 - y1 under L∞ input changes: product of induced norms.
let lip = 1;
tiny.forEach(({ W, nin, nout }, li) => {
  const last = li === tiny.length - 1;
  if (last) {
    // row vector (e0 - e1)ᵀ W: L1 norm of its entries
    let s = 0;
    for (let i = 0; i < nin; i++) s += Math.abs(W[i * nout] - W[i * nout + 1]);
    lip *= s;
  } else {
    // ||Wᵀ||_{∞→∞} = max over outputs of sum |W_ij|
    let m = 0;
    for (let j = 0; j < nout; j++) {
      let s = 0;
      for (let i = 0; i < nin; i++) s += Math.abs(W[i * nout + j]);
      m = Math.max(m, s);
    }
    lip *= m;
  }
});
const grid = 1 / N; // every point is within this L∞ distance of a grid point
const satThreshold = Number((0.95 * best).toPrecision(6));
const unsatThreshold = Number((best + lip * grid * 1.01).toPrecision(6));

const header = (title) => `; ${title}
; Network: tiny-relu.onnx (2 inputs, two hidden layers of 8 ReLUs, 2 outputs).
; Generated by tests/make-examples.js.

(declare-const X_0 Real)
(declare-const X_1 Real)
(declare-const Y_0 Real)
(declare-const Y_1 Real)

(assert (>= X_0 -1))
(assert (<= X_0 1))
(assert (>= X_1 -1))
(assert (<= X_1 1))
`;

writeFileSync(
  new URL("tiny-relu-sat.vnnlib", out),
  `${header("Unsafe if Y_0 exceeds Y_1 by a margin that some inputs reach (sat).")}
; Grid search found max(Y_0 - Y_1) = ${best.toPrecision(6)}; the threshold is 95% of it.
(assert (>= (- Y_0 Y_1) ${satThreshold}))
`,
);
writeFileSync(
  new URL("tiny-relu-unsat.vnnlib", out),
  `${header("Unsafe if Y_0 exceeds Y_1 by more than is possible (unsat).")}
; max(Y_0 - Y_1) <= grid max ${best.toPrecision(6)} + Lipschitz bound ${lip.toPrecision(4)} x grid spacing ${grid},
; so no input reaches this threshold. The attack should report "unknown", never "sat".
(assert (>= (- Y_0 Y_1) ${unsatThreshold}))
`,
);

// ---- Example 2: 2 → 16 → 16 → 3 classifier and labelled points.
const clf = mlp("mlp-classifier.onnx", [2, 16, 16, 3], 2.0);
const lines = ["x0,x1,label"];
for (let i = 0; i < 40; i++) {
  const x = [Number((rng() * 2 - 1).toFixed(3)), Number((rng() * 2 - 1).toFixed(3))];
  const y = forward(clf, x.map(Math.fround));
  const label = y.indexOf(Math.max(...y));
  lines.push(`${x[0]},${x[1]},${label}`);
}
writeFileSync(new URL("mlp-points.csv", out), lines.join("\n") + "\n");

console.log({ best, lip, satThreshold, unsatThreshold });
